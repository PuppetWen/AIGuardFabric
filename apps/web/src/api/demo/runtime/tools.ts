export const demoMcpTools: McpTool[] = toolSeeds.map((seed, index) => ({
  id: `tool-${String(index + 1).padStart(4, '0')}`,
  serverId: seed.serverId,
  name: seed.name,
  description: seed.description,
  capabilities: seed.capabilities,
  riskLevel: seed.riskLevel,
  invocations24h: seed.baseInvocations,
  sensitiveParams: seed.sensitiveParams,
  datasources: seed.datasources,
}));

export function toolsForServer(serverId: string): McpTool[] {
  return demoMcpTools.filter((tool) => tool.serverId === serverId);
}
