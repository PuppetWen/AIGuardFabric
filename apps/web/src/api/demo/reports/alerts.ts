export const demoAlerts: Alert[] = alertSeeds.map((seed) => {
  const asset = demoAssetById.get(seed.assetId);
  return {
    id: seed.id,
    title: seed.title,
    severity: seed.severity,
    domain: seed.domain,
    status: seed.status,
    source: seed.source,
    assetId: seed.assetId,
    assetName: asset?.name ?? seed.assetId,
    findingId: seed.findingId,
    aggregateCount: seed.aggregateCount,
    firstSeenAt: agoMinutes(seed.firstSeenMinutes),
    lastSeenAt: agoMinutes(seed.lastSeenMinutes),
    slaDueAt:
      seed.slaRemainingMinutes >= 0
        ? aheadHours(seed.slaRemainingMinutes / 60)
        : agoHours(Math.abs(seed.slaRemainingMinutes) / 60),
    slaBreached: seed.slaRemainingMinutes < 0,
    assignee: seed.assignee,
    escalationTier: seed.escalationTier,
    description: seed.description,
  };
});
