interface PolicySeed {
  id: string;
  name: string;
  description: string;
  action: PolicyAction;
  priority: number;
  lifecycle: PolicyLifecycle;
  interceptPoints: InterceptPoint[];
  expression: string;
  code: string;
  codeLanguage: 'rego' | 'cel';
  enabled: boolean;
  dryRun: boolean;
  hitCount24h: number;
  blockedCount24h: number;
  signature: PolicySignature['status'];
  signer: string;
  updatedDays: number;
  author: string;
}

function sig(status: PolicySignature['status'], signer: string, keyId: string, digest: string): PolicySignature {
  return {
    status,
    signer,
    keyId,
    digest,
    signedAt: status === 'unsigned' ? null : agoDays(3),
  };
}

